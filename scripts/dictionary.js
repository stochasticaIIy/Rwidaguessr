export function localizeTerm(frenchStr) {
  if (!frenchStr) return { en: '', ar: '' };
  const cleaned = String(frenchStr).trim();
  if (terms[cleaned]) {
    return terms[cleaned];
  }
  // Try case-insensitive lookup
  const lower = cleaned.toLowerCase();
  for (const [key, val] of Object.entries(terms)) {
    if (key.toLowerCase() === lower) return val;
  }

  // Handle numbers with units (e.g., "68 000 km" or "8 CV" or "2021")
  const kmMatch = cleaned.match(/^([\d\s]+)\s*km$/i);
  if (kmMatch) {
    const num = kmMatch[1].trim();
    return { en: `${num} km`, ar: `${num} كم` };
  }
  const cvMatch = cleaned.match(/^(\d+)\s*CV$/i);
  if (cvMatch) {
    return { en: `${cvMatch[1]} hp`, ar: `${cvMatch[1]} خيل جبائي` };
  }
  const cm3Match = cleaned.match(/^([\d\s]+)\s*(?:cm3|cm³|cc)$/i);
  if (cm3Match) {
    return { en: `${cm3Match[1].trim()} cc`, ar: `${cm3Match[1].trim()} سم³` };
  }
  if (/^\d{4}$/.test(cleaned)) {
    return { en: cleaned, ar: cleaned };
  }

  // Fallback: bilingual-ready with the cleaned string
  return { en: cleaned, ar: cleaned };
}
